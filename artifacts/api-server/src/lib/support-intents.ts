export function getSupportIntentReply(message: string) {
  const query = message
    .trim()
    .toLocaleLowerCase("th-TH")
    .replace(/[^\p{L}\p{M}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ");

  if (!query) return null;

  if (/(คุณคืออะไร|เป็นใคร|ทำอะไรได้|แนะนำตัว)/u.test(query)) {
    return "ผมคือ KnightSupport ผู้ช่วยของ Knight Furnich ครับ ผมช่วยค้นหา SKU อ่างล้างหน้า รหัสสีหิน ราคา ขนาด วิดีโอ 3D 360° และแนะนำวิธีใช้งานหน้า Knight Basins ได้ ลองพิมพ์รหัส เช่น KF020 หรือ BW010 หรือถามวิธีใช้งานได้เลยครับ";
  }

  if (/(สวัสดี|หวัดดี|hello|hi|ทักทาย)/u.test(query)) {
    return "สวัสดีครับ ยินดีช่วยค้นหาข้อมูลอ่างล้างหน้า หินสังเคราะห์ และช่วยอธิบายวิธีใช้งานหน้า Knight Basins ให้ครับ";
  }

  if (/(กด|คลิก|ปุ่ม|ออก|สร้าง).*(ใบเสนอราคา|เสนอราคา).*(ไม่ได้|ไม่ออก|ไม่ทำงาน|ไม่สำเร็จ|ทำอย่างไร|ทำไง|ยังไง)|((ใบเสนอราคา|เสนอราคา).*(ไม่ได้|ไม่ออก|ไม่ทำงาน|ไม่สำเร็จ))/u.test(query)) {
    return "ถ้ากด “ออกใบเสนอราคาทางการ” แล้วไม่ไปต่อ ให้ตรวจตามนี้ครับ\n1. ต้องมีสินค้าอ่างล้างหน้าอย่างน้อย 1 รายการ\n2. กรอกชื่อผู้ติดต่อ โทรศัพท์ อีเมล และชื่อโครงการในส่วนข้อมูลลูกค้าและหน้างาน\n3. ตรวจว่าอีเมลถูกต้อง และวันที่คาดว่าจะติดตั้งไม่ใช่วันที่ผ่านมา\n4. ถ้าเลือกหินแบบตัดและติดตั้ง ต้องกรอกขนาดอย่างน้อย 10 × 10 ซม. และเลือกสีที่มีราคา\nเมื่อกดปุ่มอีกครั้ง ระบบจะพาไปยังช่องแรกที่ยังขาดให้กรอกครับ";
  }

  if (/(วิธี(ใช้|การใช้งาน)|ใช้งาน.*(เว็บ|เว็บไซต์|knight|อ่าง)|เริ่มใช้งาน)/u.test(query)) {
    return "วิธีใช้งาน Knight Basins แบบสั้น ๆ ครับ\n1. เลือกอ่างหรือหินที่ต้องการ แล้วกดเพิ่มลงใบเสนอราคา\n2. เปิดหน้า “ใบเสนอราคา” เพื่อตรวจรายการและปรับจำนวน\n3. กรอกข้อมูลลูกค้าและหน้างานที่จำเป็น\n4. เลือกรูปแบบเอกสาร แล้วกด “ออกใบเสนอราคาทางการ”\nถ้าติดขั้นตอนไหน พิมพ์บอกอาการได้เลยครับ เช่น “กดออกใบเสนอราคาไม่ได้”";
  }

  if (/(ร้านอยู่ไหน|อยู่ที่ไหน|ที่อยู่ร้าน|พิกัดร้าน|ไปที่ร้าน|ไปยังไง)/u.test(query)) {
    return "ผมยังไม่มีข้อมูลที่อยู่หน้าร้านในระบบครับ แต่ช่วยค้นหารายละเอียดสินค้า ราคา และขนาดให้ได้ หากต้องการนัดหมายหรือสอบถามสถานที่ กรุณาติดต่อทีม Knight Furnich โดยตรงครับ";
  }

  if (/(ขอบคุณ|ขอบใจ|thank)/u.test(query)) {
    return "ยินดีครับ ถ้าต้องการดูสินค้า ราคา หรือขนาดเพิ่มเติม พิมพ์ SKU มาได้เลยครับ";
  }

  if (/(ไปเที่ยว|เที่ยวกัน|เดท|รัก|แฟน)/u.test(query)) {
    return "ผมเป็นผู้ช่วยข้อมูลสินค้า จึงไปเที่ยวด้วยไม่ได้ครับ แต่ช่วยเลือกอ่างล้างหน้าหรือหินสังเคราะห์ให้ได้เสมอ";
  }

  return null;
}