import { SUPPORT_PHONE_PRIMARY } from "./contact-info.ts";
import { identityReply, personalQuestionReply } from "./support-guest-answers.ts";
import { isIdentityQuestion, isPersonalQuestion } from "./support-signals.ts";

export function getSupportIntentReply(message: string) {
  const query = message
    .trim()
    .toLocaleLowerCase("th-TH")
    .replace(/[^\p{L}\p{M}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ");

  if (!query) return null;

  // Job 421-C: who/what are you (including "a person or a bot?") -- answered for everyone, never a login prompt.
  if (isIdentityQuestion(message)) return identityReply();
  if (isPersonalQuestion(message)) return personalQuestionReply();

  if (/(สวัสดี|หวัดดี|hello|(?<![a-z])hi(?![a-z])|ทักทาย)/u.test(query)) {
    return "สวัสดีค่ะ น้องไนท์ยินดีช่วยค้นหาข้อมูลอ่างล้างหน้า หินสังเคราะห์ และช่วยอธิบายวิธีใช้งานหน้า Knight Basins ให้ค่ะ";
  }

  if (/(กด|คลิก|ปุ่ม|ออก|สร้าง).*(ใบเสนอราคา|เสนอราคา).*(ไม่ได้|ไม่ออก|ไม่ทำงาน|ไม่สำเร็จ|ทำอย่างไร|ทำไง|ยังไง)|((ใบเสนอราคา|เสนอราคา).*(ไม่ได้|ไม่ออก|ไม่ทำงาน|ไม่สำเร็จ))/u.test(query)) {
    return "ถ้ากด “ออกใบเสนอราคาทางการ” แล้วไม่ไปต่อ ให้ตรวจตามนี้ค่ะ\n1. ต้องมีสินค้าอ่างล้างหน้าอย่างน้อย 1 รายการ\n2. กรอกชื่อผู้ติดต่อ โทรศัพท์ อีเมล และชื่อโครงการในส่วนข้อมูลลูกค้าและหน้างาน\n3. ตรวจว่าอีเมลถูกต้อง และวันที่คาดว่าจะติดตั้งไม่ใช่วันที่ผ่านมา\n4. ถ้าเลือกหินแบบตัดและติดตั้ง ต้องกรอกขนาดอย่างน้อย 10 × 10 ซม. และเลือกสีที่มีราคา\nเมื่อกดปุ่มอีกครั้ง ระบบจะพาไปยังช่องแรกที่ยังขาดให้กรอกค่ะ";
  }

  if (/(วิธี(ใช้|การใช้งาน)|ใช้งาน.*(เว็บ|เว็บไซต์|knight|อ่าง)|เริ่มใช้งาน)/u.test(query)) {
    return "วิธีใช้งาน Knight Basins แบบสั้น ๆ ค่ะ\n1. เลือกอ่างหรือหินที่ต้องการ แล้วกดเพิ่มลงใบเสนอราคา\n2. เปิดหน้า “ใบเสนอราคา” เพื่อตรวจรายการและปรับจำนวน\n3. กรอกข้อมูลลูกค้าและหน้างานที่จำเป็น\n4. เลือกรูปแบบเอกสาร แล้วกด “ออกใบเสนอราคาทางการ”\nถ้าติดขั้นตอนไหน พิมพ์บอกอาการได้เลยค่ะ เช่น “กดออกใบเสนอราคาไม่ได้”";
  }

  if (/(ร้านอยู่ไหน|อยู่ที่ไหน|ที่อยู่ร้าน|พิกัดร้าน|ไปที่ร้าน|ไปยังไง)/u.test(query)) {
    return `น้องไนท์ยังไม่มีข้อมูลที่อยู่หน้าร้านในระบบค่ะ แต่ช่วยค้นหารายละเอียดสินค้า ราคา และขนาดให้ได้ หากต้องการนัดหมายหรือสอบถามสถานที่ กรุณาติดต่อทีม Knight Furnich โดยตรงที่ ${SUPPORT_PHONE_PRIMARY} ค่ะ`;
  }

  if (/(ขอบคุณ|ขอบใจ|thank)/u.test(query)) {
    return "ยินดีค่ะ ถ้าต้องการดูสินค้า ราคา หรือขนาดเพิ่มเติม พิมพ์ SKU มาได้เลยค่ะ";
  }

  if (/(ไปเที่ยว|เที่ยวกัน|เดท|รัก|แฟน)/u.test(query)) {
    return "น้องไนท์เป็นผู้ช่วยข้อมูลสินค้า จึงไปเที่ยวด้วยไม่ได้ค่ะ แต่ช่วยเลือกอ่างล้างหน้าหรือหินสังเคราะห์ให้ได้เสมอ";
  }

  return null;
}